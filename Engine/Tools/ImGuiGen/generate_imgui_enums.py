"""Writes LuminaSharp's ImGui enums from imgui.h, run again after updating ThirdParty/imgui."""

import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HEADER = os.path.join(ROOT, 'Source', 'ThirdParty', 'imgui', 'imgui.h')
OUTPUT = os.path.join(ROOT, 'Source', 'LuminaSharp', 'ImGui', 'ImGuiEnums.g.cs')

HASH = chr(35)

# The enums the C# surface takes, each with whether its values combine as flags.
ENUMS = [
    ('ImGuiWindowFlags', True),
    ('ImGuiChildFlags', True),
    ('ImGuiInputTextFlags', True),
    ('ImGuiTreeNodeFlags', True),
    ('ImGuiPopupFlags', True),
    ('ImGuiSelectableFlags', True),
    ('ImGuiComboFlags', True),
    ('ImGuiTabBarFlags', True),
    ('ImGuiTabItemFlags', True),
    ('ImGuiFocusedFlags', True),
    ('ImGuiHoveredFlags', True),
    ('ImGuiColorEditFlags', True),
    ('ImGuiSliderFlags', True),
    ('ImGuiTableFlags', True),
    ('ImGuiTableColumnFlags', True),
    ('ImGuiTableRowFlags', True),
    ('ImGuiCond', True),
    ('ImGuiCol', False),
    ('ImGuiStyleVar', False),
    ('ImGuiMouseButton', False),
]


def strip_comment(line):
    index = line.find('//')
    return line if index < 0 else line[:index]


def read_enum(lines, name):
    start = None
    for index, line in enumerate(lines):
        if re.match(r'^enum ' + re.escape(name) + r'_\s*$', line.strip()):
            start = index
            break
    if start is None:
        raise RuntimeError('enum ' + name + '_ not found in imgui.h')

    entries = []
    depth_skip = 0
    for line in lines[start + 2:]:
        stripped = line.strip()
        if stripped.startswith('};'):
            break
        if stripped.startswith(HASH + 'ifndef IMGUI_DISABLE_OBSOLETE') or stripped.startswith(HASH + 'ifdef IMGUI_ENABLE_OBSOLETE'):
            depth_skip += 1
            continue
        if stripped.startswith(HASH + 'if'):
            depth_skip += 1 if depth_skip else 0
            continue
        if stripped.startswith(HASH + 'endif'):
            depth_skip = max(depth_skip - 1, 0)
            continue
        if depth_skip or stripped.startswith(HASH):
            continue

        body = strip_comment(stripped).strip().rstrip(',').strip()
        if not body:
            continue
        match = re.match(r'^(' + re.escape(name) + r'_\w+)\s*(?:=\s*(.+))?$', body)
        if not match:
            continue
        member = match.group(1)[len(name) + 1:]
        value = match.group(2)
        if value is not None:
            value = re.sub(re.escape(name) + r'_(\w+)', r'\1', value)
            if re.search(r'ImGui\w+_', value):
                continue
        entries.append((member, value))
    return entries


def main():
    with open(HEADER, encoding='utf-8') as handle:
        lines = handle.read().splitlines()

    out = []
    out.append('// <auto-generated/> by Engine/Tools/ImGuiGen/generate_imgui_enums.py from ThirdParty/imgui/imgui.h.')
    out.append('namespace LuminaSharp;')
    out.append('')
    for name, flags in ENUMS:
        if flags:
            out.append('[System.Flags]')
        out.append('public enum ' + name + ' : int')
        out.append('{')
        for member, value in read_enum(lines, name):
            out.append('    ' + member + ('' if value is None else ' = ' + value) + ',')
        out.append('}')
        out.append('')

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(out).rstrip() + '\n')
    print('wrote ' + OUTPUT)


if __name__ == '__main__':
    main()
